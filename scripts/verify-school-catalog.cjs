const assert = require("node:assert/strict");
const { runtime } = require("./security-test-runtime.cjs");
const { load } = runtime({ window: { localStorage: { getItem: () => null }, sessionStorage: { getItem: () => null } } });
const { highSchoolMaster, highSchoolDraft, searchHighSchools, programsForSchool } = load("@/lib/high-school-master");
const { attachUniversityMasterIds, isSameUniversityFaculty } = load("@/lib/university-candidate");
const { findUniversityMasterByExactName } = load("@/lib/university-master");
const { buildShinromiiBackup, parseShinromiiBackupJson } = load("@/lib/shinromii-backup");
const programs = require("../data/high-school-master/programs.json");
const schools = new Set(highSchoolMaster.schools.map(s => s.code));
assert.equal(schools.size, highSchoolMaster.schools.length);
for (const [code, rows] of Object.entries(programs.bySchool)) {
  assert.ok(schools.has(code));
  assert.ok(rows.every(p => programs.sources[p.source]));
}
const school = searchHighSchools("錦城高校")[0];
const [first, second] = programsForSchool(school.code);
const a = highSchoolDraft(school.name, school, first);
const b = highSchoolDraft(school.name, school, second);
assert.equal(isSameUniversityFaculty(a, b), false);
assert.equal(isSameUniversityFaculty(a, { ...a }), true);
assert.equal(isSameUniversityFaculty(a, { ...a, schoolKind: undefined }), false);
assert.equal(highSchoolDraft(school.name, school).masterAcademicYear, "2026");
assert.equal(a.masterAcademicYear, "2027");
assert.equal(attachUniversityMasterIds([highSchoolDraft("昭和女子大学")]).changed, false);
const showa = findUniversityMasterByExactName("昭和女子大学");
assert.ok(showa.faculties.some(f => f.name === "総合情報学部"));
const sample = load("@/lib/shinromii-demo-sample").createDemoSample();
const old = { ...sample.universityCandidates[0], university: "旧校名", faculty: "旧学部", masterAcademicYear: "2025" };
sample.universityCandidates = [old, a, b];
const backup = buildShinromiiBackup(sample);
const parsed = parseShinromiiBackupJson(JSON.stringify(backup));
assert.ok(parsed.ok);
const [legacy, restoredA, restoredB] = parsed.storage.universityCandidates;
assert.equal(legacy.schoolKind, undefined);
assert.equal(legacy.university, "旧校名");
assert.equal(legacy.faculty, "旧学部");
assert.equal(legacy.masterAcademicYear, "2025");
assert.equal(restoredA.highSchoolCode, school.code);
assert.equal(restoredA.masterSourceUrl, programs.sources[first.source].url);
assert.equal(restoredB.department, second.course);
console.log("PASS school catalogs: references, school stages, distinct courses, academic years and historical backup snapshots");
